function wav(parts, channels = 1) {
  const rate = 22050
  const count = parts.reduce((sum, part) => sum + Math.round(part.seconds * rate), 0)
  const buffer = Buffer.alloc(44 + count * channels * 2)
  buffer.write('RIFF', 0); buffer.writeUInt32LE(buffer.length - 8, 4); buffer.write('WAVEfmt ', 8)
  buffer.writeUInt32LE(16, 16); buffer.writeUInt16LE(1, 20); buffer.writeUInt16LE(channels, 22)
  buffer.writeUInt32LE(rate, 24); buffer.writeUInt32LE(rate * channels * 2, 28)
  buffer.writeUInt16LE(channels * 2, 32); buffer.writeUInt16LE(16, 34); buffer.write('data', 36); buffer.writeUInt32LE(count * channels * 2, 40)
  let offset = 44
  for (const part of parts) {
    const length = Math.round(part.seconds * rate)
    const frequency = part.midi === null ? 0 : 440 * 2 ** ((part.midi - 69) / 12)
    for (let i = 0; i < length; i++) {
      const value = Math.round(10000 * Math.sin(2 * Math.PI * frequency * i / rate) * Math.min(1, i / 100, (length - i) / 100))
      for (let channel = 0; channel < channels; channel++) { buffer.writeInt16LE(channel === channels - 1 ? value : 0, offset); offset += 2 }
    }
  }
  return buffer.toString('base64')
}
