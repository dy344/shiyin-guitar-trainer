const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const path = require('node:path')
const timer = setTimeout(() => { console.error('桌面测试超时'); app.exit(1) }, 20000)
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 1440, height: 900, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } })
  await window.loadFile(path.join(__dirname, '..', 'dist', 'index.html'))
  const result = await window.webContents.executeJavaScript(`({mounted: !!document.querySelector('.app-shell'), styled: getComputedStyle(document.querySelector('.app-shell')).display, isolated: typeof window.require === 'undefined', microphone: !!navigator.mediaDevices?.getUserMedia})`)
  assert.equal(result.mounted, true)
  assert.equal(result.styled, 'grid')
  assert.equal(result.isolated, true)
  assert.equal(result.microphone, true)
  console.log('PASS: 页面加载、样式加载、Node 隔离、麦克风 API')
  clearTimeout(timer)
  app.exit(0)
}).catch((error) => { console.error(error); clearTimeout(timer); app.exit(1) })
