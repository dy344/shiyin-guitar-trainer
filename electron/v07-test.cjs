const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
app.disableHardwareAcceleration()
let stage = '启动'
const timeout = setTimeout(() => { console.error('v0.7 界面测试超时：' + stage); app.exit(1) }, 45000)
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 1440, height: 1000, webPreferences: { offscreen: true, contextIsolation: true, sandbox: true, nodeIntegration: false, partition: `v07-${Date.now()}` } })
  const errors = [], opened = []
  window.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message) })
  window.webContents.setWindowOpenHandler(({ url }) => { opened.push(url); return { action: 'deny' } })
  if (process.argv.includes('--local-web')) await window.loadURL('http://127.0.0.1:5188/')
  else await window.loadFile(path.join(__dirname, '..', 'dist', 'index.html'))
  const evaluate = expression => window.webContents.executeJavaScript(expression, true)
  const poll = async expression => {
    for (let i = 0; i < 150; i++) {
      if (await evaluate(expression)) return
      await new Promise(resolve => setTimeout(resolve, 40))
    }
    throw new Error(`界面检查超时: ${expression}; ${await evaluate(`document.querySelector('.learning-message')?.textContent`)}`)
  }
  const settle = () => new Promise(resolve => setTimeout(resolve, 60))
  const click = async text => {
    await evaluate(`(() => { const button = Array.from(document.querySelectorAll('button')).find(b => b.textContent === ${JSON.stringify(text)} && b.getClientRects().length); if (!button || button.disabled) throw new Error('按钮不可用：' + ${JSON.stringify(text)}); button.click(); })()`)
    await settle()
  }
  const input = async (label, value) => {
    await evaluate(`(() => { const control = document.querySelector('[aria-label="${label}"]'); const prototype = control.tagName === 'SELECT' ? HTMLSelectElement.prototype : control.tagName === 'TEXTAREA' ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(prototype, 'value').set.call(control, ${JSON.stringify(value)}); control.dispatchEvent(new Event(control.tagName === 'SELECT' ? 'change' : 'input', {bubbles:true})); })()`)
    await settle()
  }
  const upload = async raw => {
    await evaluate(`(() => { const control = document.querySelector('[aria-label="选择完整备份文件"]'); const data = new DataTransfer(); data.items.add(new File([${JSON.stringify(raw)}], 'backup.json', {type:'application/json'})); control.files = data.files; control.dispatchEvent(new Event('change', {bubbles:true})); })()`)
  }
  const stored = () => evaluate(`JSON.parse(localStorage.getItem('shiyin.learning-resources.v1'))?.resources ?? []`)
  const capture = async name => { await new Promise(resolve => setTimeout(resolve, 200)); await fs.writeFile(path.join(output, name), (await window.webContents.capturePage()).toPNG()) }
  const output = await fs.mkdtemp(path.join(os.tmpdir(), 'shiyin-v07-'))
  await poll(`document.querySelector('.app-shell') !== null`)
  assert.equal(await evaluate(`document.querySelector('vite-error-overlay') === null`), true)
  stage = '站外搜索与空输入'
  await click('找谱学习')
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.pitch-card')).display`), 'none')
  assert.equal(await evaluate(`document.querySelector('[data-score-editor]').hidden`), true)
  await click('查找曲谱与教程')
  await poll(`document.querySelector('.learning-message').textContent.includes('请输入')`)
  assert.equal(await evaluate(`document.querySelectorAll('.learning-search-links a').length`), 0)
  await input('目标歌名', '晴天 & 测试?')
  await input('找谱版本', 'fingerstyle')
  await click('查找曲谱与教程')
  await poll(`document.querySelectorAll('.learning-search-links a').length === 3`)
  const links = await evaluate(`Array.from(document.querySelectorAll('.learning-search-links a')).map(a => ({href:a.href,target:a.target,rel:a.rel}))`)
  assert.ok(links.every(link => link.target === '_blank' && link.rel === 'noopener noreferrer'))
  assert.match(new URL(links[0].href).searchParams.get('wd'), /晴天 & 测试\? 吉他 指弹/)
  assert.match(new URL(links[2].href).searchParams.get('keyword'), /教程 慢速/)
  await evaluate(`document.querySelector('.learning-search-links a').click()`)
  await poll(`true`)
  assert.deepEqual(opened, [links[0].href])
  assert.equal(window.webContents.getURL().startsWith(process.argv.includes('--local-web') ? 'http://127.0.0.1:5188/' : 'file:'), true)
  await capture('search-desktop.png')
  stage = '无效网址保护、收藏与状态筛选'
  await input('资料标题', '喜欢的演奏')
  await input('资料网址', 'javascript:alert(1)')
  await click('保存学习资料')
  assert.equal(await evaluate(`localStorage.getItem('shiyin.learning-resources.v1')`), null)
  assert.ok(await evaluate(`document.querySelector('.learning-message').textContent.includes('https://')`))
  await input('资料网址', 'https://www.bilibili.com/video/example?from=study')
  await input('资料类型', 'video')
  await input('关联本地曲谱', 'ode-example')
  await input('学习笔记', '01:20 的第 2 小节，先听再练\n关注换弦')
  await click('保存学习资料')
  await poll(`document.querySelectorAll('.resource-list li').length === 1`)
  const original = (await stored())[0]
  assert.equal(original.kind, 'video')
  assert.equal(original.scoreId, 'ode-example')
  await input('喜欢的演奏的学习状态', 'learning')
  assert.equal((await stored())[0].status, 'learning')
  await input('筛选学习状态', 'done')
  assert.equal(await evaluate(`document.querySelectorAll('.resource-list li').length`), 0)
  await input('筛选学习状态', 'all')
  await input('筛选学习资料', '关注换弦')
  assert.equal(await evaluate(`document.querySelectorAll('.resource-list li').length`), 1)
  await input('筛选学习资料', '不存在')
  assert.equal(await evaluate(`document.querySelectorAll('.resource-list li').length`), 0)
  await input('筛选学习资料', '')
  stage = '编辑、重复网址、删除撤销与持久化'
  await click('编辑资料')
  await input('资料标题', '慢速演奏')
  await input('学习笔记', '已练第 1 小节，第 2 小节慢练')
  await click('保存资料修改')
  assert.equal((await stored())[0].id, original.id)
  assert.equal((await stored())[0].status, 'learning')
  await input('资料标题', '重复收藏')
  await input('资料网址', original.url)
  await click('保存学习资料')
  assert.ok(await evaluate(`document.querySelector('.learning-message').textContent.includes('已收藏')`))
  assert.equal((await stored()).length, 1)
  await click('移除资料')
  assert.equal((await stored()).length, 0)
  await click('撤销删除资料')
  assert.equal((await stored())[0].title, '慢速演奏')
  await window.reload()
  await poll(`document.querySelector('.app-shell') !== null`)
  await click('找谱学习')
  assert.equal(await evaluate(`document.querySelectorAll('.resource-list li').length`), 1)
  assert.equal(await evaluate(`document.querySelector('.resource-list select').value`), 'learning')
  await evaluate(`document.querySelector('.resource-library').scrollIntoView({block:'start'})`)
  await capture('resources-desktop.png')
  stage = '练习建议与关联曲谱跳转'
  assert.ok(await evaluate(`document.querySelectorAll('.study-cards article').length >= 1`))
  const measure = await evaluate(`document.querySelector('.study-cards button').textContent`)
  await click(measure)
  assert.equal(await evaluate(`document.querySelector('[data-learning-container]').hidden`), true)
  const range = await evaluate(`({start:Number(document.querySelector('[aria-label="起始音符"]').value),end:Number(document.querySelector('[aria-label="结束音符"]').value),bpm:document.querySelector('[aria-label="休止计时速度"]').value})`)
  assert.ok(range.end >= range.start)
  assert.ok(range.end - range.start < 15)
  assert.equal(range.bpm, '52')
  assert.equal(await evaluate(`document.querySelector('.workspace footer button').textContent`), '开始监听')
  await click('找谱学习')
  await click('去练这首')
  assert.equal(await evaluate(`document.querySelector('[aria-label="起始音符"]').value`), '1')
  assert.equal(await evaluate(`document.querySelector('[aria-label="结束音符"]').value`), '15')
  stage = '新版完整备份与旧版兼容'
  const download = new Promise((resolve, reject) => {
    window.webContents.session.once('will-download', (_, item) => {
      const destination = path.join(output, item.getFilename())
      item.setSavePath(destination)
      item.once('done', (_, state) => state === 'completed' ? resolve(destination) : reject(new Error(state)))
    })
  })
  await click('下载完整备份')
  const rawBackup = await fs.readFile(await download, 'utf8')
  const backup = JSON.parse(rawBackup)
  assert.equal(backup.version, 2)
  assert.deepEqual(backup.resources, await stored())
  await click('找谱学习')
  await click('移除资料')
  await click('曲谱练习')
  await upload(rawBackup)
  await poll(`document.querySelector('.restore-confirm') !== null`)
  assert.ok(await evaluate(`document.querySelector('.restore-confirm').textContent.includes('学习资料也将全部替换')`))
  await click('确认替换并恢复')
  await click('找谱学习')
  assert.deepEqual(await stored(), backup.resources)
  assert.equal(await evaluate(`document.querySelectorAll('.resource-list li').length`), 1)
  await click('曲谱练习')
  const legacy = { ...backup, version: 1 }
  delete legacy.resources
  await upload(JSON.stringify(legacy))
  await poll(`document.querySelector('.restore-confirm') !== null`)
  assert.ok(await evaluate(`document.querySelector('.restore-confirm').textContent.includes('保留本机现有收藏')`))
  await click('确认替换并恢复')
  assert.deepEqual(await stored(), backup.resources)
  stage = '存储失败与损坏保护'
  await click('找谱学习')
  await input('资料标题', '存储失败时保留表单')
  await input('资料网址', 'https://example.com/new')
  await evaluate(`window.originalSetItem = Storage.prototype.setItem; Storage.prototype.setItem = function(key, value) { if (key === 'shiyin.learning-resources.v1') throw new Error('测试：存储空间不足'); return window.originalSetItem.call(this, key, value); }; true`)
  await click('保存学习资料')
  assert.deepEqual(await stored(), backup.resources)
  assert.equal(await evaluate(`document.querySelector('[aria-label="资料标题"]').value`), '存储失败时保留表单')
  assert.ok(await evaluate(`document.querySelector('.learning-message').textContent.includes('存储空间不足')`))
  await evaluate(`Storage.prototype.setItem = window.originalSetItem; localStorage.setItem('shiyin.learning-resources.v1', '{bad'); true`)
  await window.reload()
  await poll(`document.querySelector('.app-shell') !== null`)
  await click('找谱学习')
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('button')).find(b => b.textContent === '保存学习资料').disabled`), true)
  assert.equal(await evaluate(`localStorage.getItem('shiyin.learning-resources.v1')`), '{bad')
  await click('曲谱练习')
  await upload(rawBackup)
  await poll(`document.querySelector('.restore-confirm') !== null`)
  await click('确认替换并恢复')
  await click('找谱学习')
  assert.deepEqual(await stored(), backup.resources)
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('button')).find(b => b.textContent === '保存学习资料').disabled`), false)
  stage = '孤立关联与窄屏布局'
  const orphan = { ...backup.resources[0], scoreId: 'missing-score' }
  await evaluate(`localStorage.setItem('shiyin.learning-resources.v1', ${JSON.stringify(JSON.stringify({version:1,resources:[orphan]}))}); true`)
  await window.reload()
  await poll(`document.querySelector('.app-shell') !== null`)
  await click('找谱学习')
  assert.ok(await evaluate(`document.querySelector('.resource-host').textContent.includes('原关联曲谱不在')`))
  await click('编辑资料')
  assert.equal(await evaluate(`document.querySelector('[aria-label="关联本地曲谱"]').value`), 'missing-score')
  await click('取消编辑')
  window.setSize(390, 844)
  await evaluate(`scrollTo(0, 0)`)
  await capture('study-mobile.png')
  assert.ok(await evaluate(`document.documentElement.scrollWidth <= innerWidth + 1`))
  await evaluate(`document.querySelector('.resource-library').scrollIntoView({block:'start'})`)
  await capture('resources-mobile.png')
  assert.ok(await evaluate(`document.documentElement.scrollWidth <= innerWidth + 1`))
  assert.deepEqual(errors, [])
  console.log('PASS: v0.7 搜索编码与站外跳转、无效输入、收藏编辑和去重、手动状态筛选、删除撤销、刷新持久化、难点练习与关联跳转、完整备份 v2 与旧版兼容、写入失败和损坏保护、孤立关联、桌面与窄屏；证据 ' + output)
  clearTimeout(timeout)
  app.exit(0)
}).catch(error => { console.error('失败阶段：' + stage, error); clearTimeout(timeout); app.exit(1) })
