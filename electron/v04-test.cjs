const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
app.disableHardwareAcceleration()
const timeout = setTimeout(() => { console.error('v0.4 界面测试超时'); app.exit(1) }, 45000)
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 1440, height: 1000, webPreferences: { offscreen: true, contextIsolation: true, sandbox: true, nodeIntegration: false, partition: `v04-${Date.now()}` } })
  const errors = []
  window.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message) })
  if (process.argv.includes('--local-web')) await window.loadURL('http://127.0.0.1:5188/')
  else await window.loadFile(path.join(__dirname, '..', 'dist', 'index.html'))
  const evaluate = expression => window.webContents.executeJavaScript(expression, true)
  const poll = async expression => {
    for (let i = 0; i < 150; i++) {
      if (await evaluate(expression)) return
      await new Promise(resolve => setTimeout(resolve, 40))
    }
    throw new Error(`界面检查超时: ${expression}`)
  }
  const click = async text => { await evaluate(`Array.from(document.querySelectorAll('button')).find(b => b.textContent === ${JSON.stringify(text)}).click()`); await new Promise(resolve => setTimeout(resolve, 70)) }
  const select = async (label, value) => {
    await evaluate(`(() => { const input = document.querySelector('[aria-label="${label}"]'); const setter = Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set; setter.call(input, ${JSON.stringify(value)}); input.dispatchEvent(new Event('change', {bubbles:true})); })()`)
    await new Promise(resolve => setTimeout(resolve, 70))
  }
  const file = async raw => {
    await evaluate(`(() => { const input = document.querySelector('[aria-label="选择完整备份文件"]'); const data = new DataTransfer(); data.items.add(new File([${JSON.stringify(raw)}], 'backup.json', {type:'application/json'})); input.files = data.files; input.dispatchEvent(new Event('change', {bubbles:true})); })()`)
  }
  const output = await fs.mkdtemp(path.join(os.tmpdir(), 'shiyin-v04-'))
  assert.ok((await window.webContents.getTitle()).includes('拾音'))
  await poll(`document.querySelector('.app-shell') !== null`)
  assert.equal(await evaluate(`document.querySelector('vite-error-overlay') === null`), true)
  await new Promise(resolve => setTimeout(resolve, 250))
  await fs.writeFile(path.join(output, 'initial.png'), (await window.webContents.capturePage()).toPNG())
  await click('曲谱练习')
  await click('后插入音符')
  assert.equal(await evaluate(`document.querySelectorAll('.score-column').length`), 16)
  assert.ok(await evaluate(`document.querySelector('.measure-status').textContent.includes('5 / 4')`))
  await select('修改时值', '480')
  assert.ok(await evaluate(`document.querySelector('.measure-status').textContent.includes('4.5 / 4')`))
  await click('撤销')
  assert.equal(await evaluate(`document.querySelector('[aria-label="修改时值"]').value`), '960')
  await click('重做')
  assert.equal(await evaluate(`document.querySelector('[aria-label="修改时值"]').value`), '480')
  await click('后插入休止符')
  assert.equal(await evaluate(`document.querySelector('[aria-label="修改音高"]').value`), 'rest')
  await click('删除当前音')
  await click('撤销')
  assert.equal(await evaluate(`document.querySelector('[aria-label="修改音高"]').value`), 'rest')
  await click('重做')
  await evaluate(`document.querySelector('.note-editing').scrollIntoView({block:'center'})`)
  await new Promise(resolve => setTimeout(resolve, 250))
  await fs.writeFile(path.join(output, 'editor.png'), (await window.webContents.capturePage()).toPNG())
  const record = { id: 'test-history', scoreId: 'ode-example', title: '已保存练习', savedAt: '2026-10-02T01:00:00Z', start: 0, end: 1, bpm: 80, tolerance: 12, hits: 2, rests: 0, corrections: 0, laps: 1, completed: true }
  await evaluate(`localStorage.setItem('shiyin.practice-history.v1', ${JSON.stringify(JSON.stringify({ version: 1, records: [record] }))})`)
  const download = new Promise((resolve, reject) => {
    window.webContents.session.once('will-download', (_, item) => {
      const destination = path.join(output, item.getFilename())
      item.setSavePath(destination)
      item.once('done', (_, state) => state === 'completed' ? resolve(destination) : reject(new Error(state)))
    })
  })
  await click('下载完整备份')
  const savedFile = await download
  const rawBackup = await fs.readFile(savedFile, 'utf8')
  const backup = JSON.parse(rawBackup)
  assert.equal(backup.scores[0].notes.length, 16)
  assert.deepEqual(backup.records, [record])
  await click('后插入音符')
  const changed = await evaluate(`localStorage.getItem('shiyin.scores.v1')`)
  await file('{bad')
  await poll(`!document.querySelector('[aria-label="修改时值"]').disabled`)
  assert.equal(await evaluate(`localStorage.getItem('shiyin.scores.v1')`), changed)
  await file(rawBackup)
  await poll(`document.querySelector('.restore-confirm') !== null`)
  assert.equal(await evaluate(`document.querySelector('[aria-label="修改时值"]').disabled`), true)
  assert.equal(await evaluate(`localStorage.getItem('shiyin.scores.v1')`), changed)
  await click('取消恢复')
  assert.equal(await evaluate(`localStorage.getItem('shiyin.scores.v1')`), changed)
  await file(rawBackup)
  await poll(`document.querySelector('.restore-confirm') !== null`)
  await click('确认替换并恢复')
  await poll(`document.querySelector('.backup-message').textContent.includes('恢复完成')`)
  assert.deepEqual(await evaluate(`JSON.parse(localStorage.getItem('shiyin.scores.v1'))`), backup.scores)
  await click('查看历史（1）')
  assert.ok(await evaluate(`document.querySelector('.history-list').textContent.includes('命中 2')`))
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('button')).find(b => b.textContent === '撤销').disabled`), true)
  await evaluate(`document.querySelector('.backup-panel').scrollIntoView({block:'center'})`)
  await new Promise(resolve => setTimeout(resolve, 250))
  await fs.writeFile(path.join(output, 'restored.png'), (await window.webContents.capturePage()).toPNG())
  await window.reload()
  await poll(`document.querySelector('.app-shell') !== null`)
  await click('曲谱练习')
  assert.equal(await evaluate(`document.querySelectorAll('.score-column').length`), 16)
  await click('查看历史（1）')
  assert.ok(await evaluate(`document.querySelector('.history-list').textContent.includes('命中 2')`))
  window.setSize(390, 844)
  await evaluate(`document.querySelector('.note-editing').scrollIntoView({block:'start'})`)
  await new Promise(resolve => setTimeout(resolve, 250))
  assert.ok(await evaluate(`document.documentElement.scrollWidth <= innerWidth + 1`))
  await fs.writeFile(path.join(output, 'mobile.png'), (await window.webContents.capturePage()).toPNG())
  const single = { ...backup, scores: [{ ...backup.scores[0], notes: [backup.scores[0].notes[0]], meters: [{beats:4,unit:4}] }] }
  await file(JSON.stringify(single))
  await poll(`document.querySelector('.restore-confirm') !== null`)
  await click('确认替换并恢复')
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('button')).find(b => b.textContent === '删除当前音').disabled`), true)
  await click('后插入音符')
  assert.equal(await evaluate(`document.querySelectorAll('.score-column').length`), 2)
  await evaluate(`localStorage.setItem('shiyin.before-restore.v1', ${JSON.stringify(JSON.stringify({ version: 1, scores: JSON.stringify(backup.scores), history: JSON.stringify({ version: 1, records: [record] }) }))}); localStorage.setItem('shiyin.scores.v1', '[]'); localStorage.setItem('shiyin.practice-history.v1', 'bad'); true`)
  await window.reload()
  await poll(`document.querySelector('.app-shell') !== null`)
  await click('曲谱练习')
  assert.deepEqual(await evaluate(`JSON.parse(localStorage.getItem('shiyin.scores.v1'))`), backup.scores)
  assert.equal(await evaluate(`localStorage.getItem('shiyin.before-restore.v1')`), null)
  await click('查看历史（1）')
  assert.ok(await evaluate(`document.querySelector('.history-list').textContent.includes('命中 2')`))
  await evaluate(`localStorage.setItem('shiyin.scores.v1', '{bad')`)
  await window.reload()
  await poll(`document.querySelector('.app-shell') !== null`)
  await click('曲谱练习')
  assert.ok(await evaluate(`document.querySelector('.score-notice').textContent.includes('只读')`))
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('button')).find(b => b.textContent === '后插入音符').disabled`), true)
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('button')).find(b => b.textContent === '下载完整备份').disabled`), true)
  assert.equal(await evaluate(`localStorage.getItem('shiyin.scores.v1')`), '{bad')
  await file(rawBackup)
  await poll(`document.querySelector('.restore-confirm') !== null`)
  await click('确认替换并恢复')
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('button')).find(b => b.textContent === '后插入音符').disabled`), false)
  assert.deepEqual(errors, [])
  console.log('PASS: v0.4 编辑增删时值、撤销重做、小节拍数提示、完整备份下载、损坏文件保护、恢复确认与取消、曲谱与记录刷新恢复、恢复中断回滚、本地损坏只读保护与修复、最后音符保护、桌面和窄屏；截图 ' + output)
  clearTimeout(timeout)
  app.exit(0)
}).catch(error => { console.error(error); clearTimeout(timeout); app.exit(1) })
