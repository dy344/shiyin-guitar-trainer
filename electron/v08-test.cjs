const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const videoFixtures = require('./video-fixtures.cjs')
app.disableHardwareAcceleration()
let stage = '启动'
const timeout = setTimeout(() => { console.error('v0.8 测试超时：' + stage); app.exit(1) }, 55000)
app.whenReady().then(async () => {
  const createWindow = name => new BrowserWindow({ show:false, width:1440, height:1000, webPreferences:{offscreen:true,contextIsolation:true,sandbox:true,nodeIntegration:false,partition:`v08-${name}-${Date.now()}`} })
  const fixtureWindow = createWindow('fixtures')
  fixtureWindow.webContents.setAudioMuted(true)
  await fixtureWindow.loadFile(path.join(__dirname, '..', 'dist', 'index.html'))
  stage = '生成真实编码音视频'
  const fixtures = await videoFixtures(fixtureWindow)
  const window = createWindow('app')
  fixtureWindow.destroy()
  window.webContents.setAudioMuted(true)
  const errors = []
  window.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message) })
  if (process.argv.includes('--local-web')) await window.loadURL('http://127.0.0.1:5188/')
  else await window.loadFile(path.join(__dirname, '..', 'dist', 'index.html'))
  const evaluate = expression => window.webContents.executeJavaScript(expression, true)
  const settle = () => new Promise(resolve => setTimeout(resolve, 60))
  const poll = async expression => {
    for(let i=0;i<160;i++) { if(await evaluate(expression)) return; await new Promise(resolve => setTimeout(resolve,40)) }
    throw new Error(expression + ': ' + await evaluate(`document.querySelector('.video-message')?.textContent`))
  }
  const click = async text => { await evaluate(`(() => { const b=Array.from(document.querySelectorAll('button')).find(b=>b.textContent===${JSON.stringify(text)}); if(!b || b.disabled) throw new Error('按钮不可用 '+${JSON.stringify(text)}); b.click(); })()`); await settle() }
  const input = async (label,value) => { await evaluate(`(() => { const e=document.querySelector('[aria-label="${label}"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event('input',{bubbles:true})); })()`); await settle() }
  const upload = async (bytes,name) => {
    const encoded=Buffer.from(bytes).toString('base64')
    await evaluate(`(() => {const e=document.querySelector('[aria-label="导入扒谱视频"]'),data=new DataTransfer();data.items.add(new File([Uint8Array.from(atob(${JSON.stringify(encoded)}),c=>c.charCodeAt(0))],${JSON.stringify(name)}));e.files=data.files;e.dispatchEvent(new Event('change',{bubbles:true}));})()`)
  }
  const output = await fs.mkdtemp(path.join(os.tmpdir(),'shiyin-v08-'))
  const screenshot = async name => { await new Promise(resolve=>setTimeout(resolve,200)); await fs.writeFile(path.join(output,name),(await window.webContents.capturePage()).toPNG()) }
  await poll(`document.querySelector('.app-shell') !== null`)
  assert.ok(window.webContents.getTitle().includes('拾音'))
  assert.equal(await evaluate(`document.querySelector('vite-error-overlay') === null`),true)
  await click('曲谱练习')
  await evaluate(`window.revokedVideoURLs=[];window.nativeRevoke=URL.revokeObjectURL;URL.revokeObjectURL=function(url){window.revokedVideoURLs.push(url);window.nativeRevoke(url)};true`)
  const original = await evaluate(`localStorage.getItem('shiyin.scores.v1')`)
  stage = '非法、损坏与无音轨输入'
  await upload([], 'empty.mp4')
  await poll(`document.querySelector('.video-message').textContent.includes('非空')`)
  await upload([1,2,3], 'broken.mp4')
  await poll(`document.querySelector('.video-message').textContent.includes('无法读取视频')`)
  await upload(fixtures.noAudio, 'no-audio.webm')
  await poll(`document.querySelector('.video-message').textContent.includes('没有音轨')`)
  assert.equal(await evaluate(`localStorage.getItem('shiyin.scores.v1')`),original)
  stage = 'WebM 实际音轨提取与非法范围'
  await upload(fixtures.webm, '单音演奏.webm')
  await poll(`document.querySelector('.video-source')?.textContent.includes('单音演奏')`)
  await poll(`document.querySelector('.video-panel video').readyState >= 1`)
  await input('视频结束秒数','21')
  await click('生成视频扒谱草稿')
  assert.ok(await evaluate(`document.querySelector('.video-message').textContent.includes('0.25–20')`))
  await input('视频开始秒数','1')
  await input('视频结束秒数','2.5')
  await input('视频扒谱速度','120')
  await click('生成视频扒谱草稿')
  await poll(`document.querySelector('.video-draft') !== null`)
  const notes = await evaluate(`document.querySelector('.video-draft-notes').textContent`)
  assert.ok(notes.includes('G4') && notes.includes('A4') && !notes.includes('E4'), notes)
  assert.equal(await evaluate(`localStorage.getItem('shiyin.scores.v1')`),original)
  await evaluate(`document.querySelector('.video-panel').scrollIntoView({block:'start'})`)
  await screenshot('video-desktop.png')
  stage = '保存失败不丢草稿、确认入库、刷新'
  await evaluate(`window.savedSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k==='shiyin.scores.v1')throw new Error('quota');return window.savedSetItem.call(this,k,v)};true`)
  await click('将视频草稿加入曲谱库')
  assert.ok(await evaluate(`document.querySelector('.video-draft') !== null`))
  assert.equal(await evaluate(`localStorage.getItem('shiyin.scores.v1')`),original)
  await evaluate(`Storage.prototype.setItem=window.savedSetItem;true`)
  await click('将视频草稿加入曲谱库')
  const saved=await evaluate(`JSON.parse(localStorage.getItem('shiyin.scores.v1'))`)
  assert.equal(saved.length,2)
  assert.deepEqual(saved[1].notes.filter(n=>n.midi!==null).map(n=>n.midi),[67,69])
  assert.equal(await evaluate(`document.querySelector('[aria-label="示范速度"]').value`),'120')
  stage = '预览片段、停止、循环、切页暂停'
  await input('视频开始秒数','0.25')
  await input('视频结束秒数','0.75')
  await click('预览所选片段')
  await poll(`document.querySelector('.video-panel video').paused === false`)
  await poll(`document.querySelector('.video-panel video').paused === true`)
  await evaluate(`document.querySelector('[aria-label="循环视频片段"]').click()`)
  await click('预览所选片段')
  await new Promise(resolve=>setTimeout(resolve,900))
  assert.equal(await evaluate(`document.querySelector('.video-panel video').paused`),false)
  await click('停止视频预览')
  assert.equal(await evaluate(`document.querySelector('.video-panel video').paused`),true)
  await input('视频开始秒数','2.5')
  await input('视频结束秒数','3')
  await click('预览所选片段')
  await new Promise(resolve=>setTimeout(resolve,900))
  assert.equal(await evaluate(`document.querySelector('.video-panel video').paused`),false)
  await click('预览所选片段')
  await click('找谱学习')
  assert.equal(await evaluate(`document.querySelector('.video-panel video').paused`),true)
  await click('曲谱练习')
  stage = '取消与迟到结果保护'
  await evaluate(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='生成视频扒谱草稿').click();Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='找谱学习').click();true`)
  await poll(`document.querySelector('.video-message').textContent.includes('取消')`)
  await click('曲谱练习')
  assert.equal(await evaluate(`document.querySelector('.video-draft')`),null)
  await evaluate(`window.realBlobSlice=Blob.prototype.slice;Blob.prototype.slice=function(...args){const blob=window.realBlobSlice.apply(this,args);const original=blob.arrayBuffer.bind(blob);blob.arrayBuffer=async()=>{await new Promise(r=>setTimeout(r,350));return original()};return blob};true`)
  await upload(fixtures.mp4,'cancel.mp4')
  await poll(`Array.from(document.querySelectorAll('button')).some(b=>b.textContent==='取消视频处理')`)
  await click('取消视频处理')
  await evaluate(`Blob.prototype.slice=window.realBlobSlice;true`)
  await new Promise(resolve=>setTimeout(resolve,500))
  assert.ok(await evaluate(`document.querySelector('.video-message').textContent.includes('已取消')`))
  assert.equal(await evaluate(`document.querySelector('.video-draft')`),null)
  assert.equal(await evaluate(`JSON.parse(localStorage.getItem('shiyin.scores.v1')).length`),2)
  stage = 'MP4 音轨、静音与窄屏'
  await upload(fixtures.mp4,'mp4演奏.mp4')
  await poll(`document.querySelector('.video-source')?.textContent.includes('mp4演奏')`)
  await input('视频结束秒数','2.5')
  await click('生成视频扒谱草稿')
  await poll(`document.querySelector('.video-draft') !== null`)
  assert.ok(await evaluate(`document.querySelector('.video-draft-notes').textContent.includes('E4')`))
  assert.ok(await evaluate(`window.revokedVideoURLs.length >= 1`))
  window.setSize(390,844)
  await evaluate(`document.querySelector('.video-panel').scrollIntoView({block:'start'})`)
  await screenshot('video-mobile.png')
  assert.ok(await evaluate(`document.documentElement.scrollWidth <= innerWidth+1`))
  stage = 'MOV 容器实际提取'
  await upload(fixtures.mov,'手机演奏.mov')
  await poll(`document.querySelector('.video-source')?.textContent.includes('手机演奏')`)
  await click('生成视频扒谱草稿')
  await poll(`document.querySelector('.video-draft') !== null`)
  assert.ok(await evaluate(`document.querySelector('.video-draft-notes').textContent.includes('G4')`))
  await upload(fixtures.silent,'silent.webm')
  await poll(`document.querySelector('.video-source')?.textContent.includes('silent')`)
  await click('生成视频扒谱草稿')
  await poll(`document.querySelector('.video-message').textContent.includes('未检测到')`)
  await click('移除当前视频')
  assert.equal(await evaluate(`document.querySelector('.video-panel video')`),null)
  assert.ok(await evaluate(`window.revokedVideoURLs.length >= 4`))
  await window.reload()
  await poll(`document.querySelector('.app-shell') !== null`)
  await click('曲谱练习')
  assert.equal(await evaluate(`document.querySelector('[aria-label="我的曲谱"]').options.length`),2)
  assert.equal(await evaluate(`document.querySelector('.video-source')`),null)
  assert.deepEqual(errors,[])
  console.log(`PASS: WebM/MP4/MOV 编解码、区间裁剪、双声道选择、真实 Worker 音符校对、错误输入、无音轨和静音、草稿确认与写入失败保护、预览与片尾循环、取消及切页、资源释放、刷新恢复、窄屏；MP4 AAC=${fixtures.aac} AVC=${fixtures.avc}；证据 ${output}`)
  clearTimeout(timeout);app.exit(0)
}).catch(error=>{console.error('失败阶段：'+stage,error);clearTimeout(timeout);app.exit(1)})
